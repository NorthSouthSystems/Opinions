using System.Net.Http;

// This file is intended to be used exclusively by tooling, and as such, we don't want it polluting the
// NorthSouthSystems namespace. We place it into the "proper" full namespace of the Assembly.
namespace NorthSouthSystems.Opinions.BCL;

public static class VendorFiles
{
    public static async Task<string> DownloadAndMergeAsync(
        string rootNamespace,
        params ImmutableArray<string> projectRelativeFilePaths)
    {
        Throw.IfNullOrWhiteSpace(rootNamespace);
        Throw.IfDefault(projectRelativeFilePaths);
        Throw.IfZero(projectRelativeFilePaths.Length);

        var sourceBaseUri = new Uri(
            $"https://raw.githubusercontent.com/NorthSouthSystems/Opinions/{ThisAssembly.GitCommitId}/NorthSouthSystems.Opinions.BCL/");

        using var client = new HttpClient();
        client.Timeout = TimeSpan.FromSeconds(30);
        client.BaseAddress = sourceBaseUri;

        var sourceFiles =
            (await Task.WhenAll(projectRelativeFilePaths.Select(fp => DownloadAsync(client, fp)))
                .ConfigureAwait(false))
            .ToImmutableArray();

        var usings = sourceFiles
            .SelectMany(f => f.Usings)
            .Select(u => u.Trim())
            .Where(u => !u.StartsWith("using NorthSouthSystems", StringComparison.Ordinal))
            .Append("using System.Diagnostics.CodeAnalysis;")
            .Distinct(StringComparer.Ordinal)
            .OrderBy(line => line, StringComparer.Ordinal);

        List<string> output =
        [
            "// <auto-generated/>",
            "#nullable enable",
            "",
            .. usings,
            "",
            $"namespace {rootNamespace};",
            ""
        ];

        bool wasWhiteSpace = true;

        foreach (string line in sourceFiles.SelectMany(f => f.Body))
        {
            bool isWhiteSpace = string.IsNullOrWhiteSpace(line);

            if (wasWhiteSpace && isWhiteSpace)
                continue;

            wasWhiteSpace = isWhiteSpace;

            if (SourceFile.IsType(line))
            {
                output.Add("[ExcludeFromCodeCoverage]");
                output.Add(line.Replace("public ", "internal ", StringComparison.Ordinal));
            }
            else
                output.Add(line);
        }

        return string.Join("\n", output).TrimEnd('\n') + "\n";
    }

    private static async Task<SourceFile> DownloadAsync(HttpClient client, string relativeFilePath)
    {
        string contents =
            await client.GetStringAsync(new Uri(relativeFilePath, UriKind.Relative))
                .ConfigureAwait(false);

        var lines = contents.ReplaceLineEndings("\n").Split('\n').ToImmutableArray();

        return new(relativeFilePath, lines);
    }

    private record SourceFile(string RelativeFilePath, ImmutableArray<string> Lines)
    {
        private static readonly ImmutableArray<string> TypeSentinels =
            ["enum", "class", "interface", "record", "struct"];

        internal static bool IsType(string line) =>
            TypeSentinels.Any(ts => line.Contains(" " + ts + " ", StringComparison.Ordinal));

        private static bool IsPreamble(string line) =>
            string.IsNullOrWhiteSpace(line)
            || line.TrimStart().StartsWith("//", StringComparison.Ordinal)
            || !IsType(line);

        private static bool IsUsing(string line) => line.TrimStart().StartsWith("using ", StringComparison.Ordinal);

        private static bool IsNamespace(string line) =>
            line.TrimStart().StartsWith("namespace ", StringComparison.Ordinal);

        private IEnumerable<string> Preamble => Lines.TakeWhile(IsPreamble);

        internal IEnumerable<string> Usings => Preamble.Where(IsUsing);

        internal IEnumerable<string> Body =>
            Preamble.Where(line => !IsUsing(line))
                .Concat(Lines.SkipWhile(IsPreamble))
                .Where(line => !IsNamespace(line))
                .Prepend("// " + RelativeFilePath)
                .Prepend("");
    }
}
