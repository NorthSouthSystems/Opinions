using System.IO;
using System.Text.RegularExpressions;

// This file is intended to be used exclusively by tooling, and as such, we don't want it polluting the
// NorthSouthSystems namespace. We place it into the "proper" full namespace of the Assembly.
namespace NorthSouthSystems.Opinions.Entities;

public static partial class ScriptUpdatedUtcVersionTriggers
{
    [GeneratedRegex(
        @"\bCREATE\s+TABLE\s+(?:(?<schemaName>\[?\s*\w+\s*\]?)\s*\.\s*)?(?<tableName>\[?\s*\w+\s*\]?)\s*\(",
        RegexOptions.IgnoreCase | RegexOptions.Compiled | RegexOptions.Singleline)]
    private static partial Regex CreateTableRegex { get; }

    [GeneratedRegex(
        @"\[?\s*UpdatedUtc\s*\]?\s+(?<datatype>DATETIME(2\s*\(\s*\d\s*\))?)",
        RegexOptions.IgnoreCase | RegexOptions.Compiled)]
    private static partial Regex UpdatedUtcRegex { get; }

    [GeneratedRegex(
        @"\[?\s*UpdatedVersion\s*\]?\s+(?<datatype>(BIG)?INT)",
        RegexOptions.IgnoreCase | RegexOptions.Compiled)]
    private static partial Regex UpdatedVersionRegex { get; }

    [GeneratedRegex(
        @"\bCONSTRAINT\s+\[?\w+\]?\s+PRIMARY\s+KEY(?:\s+(?:CLUSTERED|NONCLUSTERED))?\s*[^\(]*\(\s*(?<columns>[^\)]+)\s*\)",
        RegexOptions.IgnoreCase | RegexOptions.Compiled | RegexOptions.Singleline)]
    private static partial Regex PrimaryKeyRegex { get; }

    private static string Normalize(string name) => name?.Trim().Trim('[', ']') ?? string.Empty;

    private static string Bracket(string name) => $"[{Normalize(name)}]";

    public static string Generate(string sqlProjectRootDirectory)
    {
        Throw.IfNull(sqlProjectRootDirectory);

        sqlProjectRootDirectory = Path.GetFullPath(sqlProjectRootDirectory);

        if (!Directory.Exists(sqlProjectRootDirectory))
            throw new DirectoryNotFoundException(sqlProjectRootDirectory);

        var sqlFilePaths = Directory
            .EnumerateFiles(sqlProjectRootDirectory, "*.sql", SearchOption.AllDirectories)
            .Where(fp => !Path.GetRelativePath(sqlProjectRootDirectory, fp)
                .Split(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar)
                .Any(part => part.Equals("bin", StringComparison.OrdinalIgnoreCase)
                    || part.Equals("obj", StringComparison.OrdinalIgnoreCase)))
            .Where(fp => !fp.Split('.').Any(part => part.Equals("generated", StringComparison.OrdinalIgnoreCase)))
            .OrderBy(path => Path.GetRelativePath(sqlProjectRootDirectory, path), StringComparer.Ordinal)
            .ToImmutableArray();

        var output = new StringBuilder();
        var errors = new List<string>();

        output.AppendLine(
            InvariantCulture,
            $"""
             -- <auto-generated/>
             --
             -- Each .sql file must contain at most one CREATE TABLE statement.
             --
             -- Tables with columns named [UpdatedUtc] and [UpdatedVersion] must have exactly 1 table-level PRIMARY KEY constraint.
             -- e.g. CONSTRAINT PK_Foo PRIMARY KEY (Col[, Col2...]).
             """);

        foreach (string filePath in sqlFilePaths)
        {
            string text = File.ReadAllText(filePath);
            string relativePath = Path.GetRelativePath(sqlProjectRootDirectory, filePath);

            var createTableMatches = CreateTableRegex.Matches(text);

            if (createTableMatches.Count == 0)
                continue;

            if (createTableMatches.Count > 1)
            {
                errors.Add($"{relativePath}: Has more than one CREATE TABLE.");
                continue;
            }

            var createTableMatch = createTableMatches[0];

            string schemaName = Normalize(createTableMatch.Groups["schemaName"].Value);
            string tableName = Normalize(createTableMatch.Groups["tableName"].Value);

            if (string.IsNullOrEmpty(schemaName))
            {
                errors.Add($"{relativePath}: CREATE TABLE must include a schema.");
                continue;
            }

            // Because createTableRegex ends with the opening parentheses, we can extract the body of the table
            // by tracking the "depth" of parentheses we are nested in.
            int startIndex = createTableMatch.Index + createTableMatch.Length;
            int depth = 1;
            int index = startIndex;

            while (index < text.Length && depth > 0)
            {
                char c = text[index++];

                if (c == '(')
                    depth++;
                else if (c == ')')
                    depth--;
            }

            if (depth != 0)
            {
                errors.Add($"{relativePath}: Unbalanced CREATE TABLE parentheses.");
                continue;
            }

            string body = text[startIndex..(index - 1)];

            var updatedUtcMatches = UpdatedUtcRegex.Matches(body);
            var updatedVersionMatches = UpdatedVersionRegex.Matches(body);

            if (updatedUtcMatches.Count == 0 && updatedVersionMatches.Count == 0)
                continue;

            if (updatedUtcMatches.Count != 1 || updatedVersionMatches.Count != 1)
            {
                errors.Add($"{relativePath}: Expected exactly one UpdatedUtc and one UpdatedVersion column.");
                continue;
            }

            string updatedUtcDatatype = updatedUtcMatches[0].Groups["datatype"].Value;

            var primaryKeyMatches = PrimaryKeyRegex.Matches(body);

            if (primaryKeyMatches.Count != 1)
            {
                errors.Add($"{relativePath}: Expected exactly one table-level PRIMARY KEY constraint.");
                continue;
            }

            var primaryKeyColumns = primaryKeyMatches[0]
                .Groups["columns"]
                .Value
                .Split(',')
                .Select(Normalize)
                .Where(string.IsNotNullAndNotWhiteSpace)
                .ToImmutableArray();

            if (primaryKeyColumns.Length == 0)
            {
                errors.Add($"{relativePath}: PRIMARY KEY contains no columns.");
                continue;
            }

            string triggerName = $"TR_{tableName}_UpdatedUtcVersion";

            string joinCondition =
                string.Join(" AND ", primaryKeyColumns.Select(Bracket).Select(c => $"t.{c} = d.{c}"));

            output.AppendLine(
                InvariantCulture,
                $"""

                 -- {relativePath}
                 CREATE TRIGGER [{schemaName}].[{triggerName}]
                 ON [{schemaName}].[{tableName}]
                 AFTER UPDATE
                 AS
                 BEGIN
                     SET NOCOUNT ON;

                     -- Guard against RECURSIVE_TRIGGERS = ON.
                     IF (UPDATE(UpdatedUtc) AND UPDATE(UpdatedVersion)) RETURN;

                     UPDATE t
                     SET t.UpdatedUtc = CAST(SYSUTCDATETIME() AS {updatedUtcDatatype}),
                         t.UpdatedVersion = d.UpdatedVersion + 1
                     FROM [{schemaName}].[{tableName}] AS t
                     JOIN deleted AS d ON {joinCondition};
                 END;

                 GO
                 """);
        }

        if (errors.Count > 0)
            throw new InvalidOperationException(string.Join(Environment.NewLine, errors));

        return output.ToString().ReplaceLineEndings("\n").TrimEnd('\n') + "\n";
    }
}
